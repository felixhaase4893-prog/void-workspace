import { addDays, toDayKey } from './dueDates';
import type { Bug, Note, Project, Snippet, Task, Workspace } from './models';

/**
 * Test data for the developer tools. Every generated item is marked twice:
 * its id starts with `devtest-` and its title with `[Test]`. Generating only
 * ever adds new items with fresh ids, so it can never overwrite real data, and
 * removing only deletes items with the `devtest-` id. Real items that were
 * linked to a test project afterwards are kept (they just lose that link).
 */

export const TEST_ID_PREFIX = 'devtest-';
export const TEST_TITLE_PREFIX = '[Test] ';

export interface TestDataContext {
  now: Date;
  createId: () => string;
}

export function isTestId(id: string): boolean {
  return id.startsWith(TEST_ID_PREFIX);
}

export interface TestDataCounts {
  projects: number;
  tasks: number;
  bugs: number;
  notes: number;
  snippets: number;
  total: number;
}

export function countTestData(workspace: Workspace): TestDataCounts {
  const count = (items: ReadonlyArray<{ id: string }>) => items.filter((item) => isTestId(item.id)).length;
  const counts = {
    projects: count(workspace.projects),
    tasks: count(workspace.tasks),
    bugs: count(workspace.bugs),
    notes: count(workspace.notes),
    snippets: count(workspace.snippets),
  };
  return { ...counts, total: counts.projects + counts.tasks + counts.bugs + counts.notes + counts.snippets };
}

function base(context: TestDataContext) {
  const iso = context.now.toISOString();
  return { id: `${TEST_ID_PREFIX}${context.createId()}`, createdAt: iso, updatedAt: iso, tagIds: [], favorite: false };
}

function testTask(context: TestDataContext, title: string, fields: Partial<Task> = {}): Task {
  return { ...base(context), title: `${TEST_TITLE_PREFIX}${title}`, description: 'Generated by the developer tools.', projectId: null, status: 'todo', priority: 'medium', dueDate: null, completedAt: null, ...fields };
}

function testBug(context: TestDataContext, title: string, fields: Partial<Bug> = {}): Bug {
  return { ...base(context), title: `${TEST_TITLE_PREFIX}${title}`, description: 'Generated by the developer tools.', projectId: null, status: 'open', priority: 'medium', dueDate: null, resolvedAt: null, ...fields };
}

/** A small, varied set: one project with tasks, bugs, notes and snippets that cover the interesting states. */
export function addTestData(workspace: Workspace, context: TestDataContext): Workspace {
  const today = toDayKey(context.now);
  const project: Project = {
    ...base(context),
    name: `${TEST_TITLE_PREFIX}Sample project`,
    description: 'Generated by the developer tools. Remove it with “Remove test data”.',
    kind: 'game',
    status: 'active',
    technologies: ['TypeScript', 'Luau'],
    links: [],
  };
  const inProject = { projectId: project.id };
  const tasks: Task[] = [
    testTask(context, 'Overdue task', { ...inProject, priority: 'high', dueDate: addDays(today, -2) }),
    testTask(context, 'Task due today', { ...inProject, dueDate: today }),
    testTask(context, 'Task due tomorrow', { ...inProject, status: 'in_progress', dueDate: addDays(today, 1) }),
    testTask(context, 'Task due in a week', { ...inProject, priority: 'low', dueDate: addDays(today, 7) }),
    testTask(context, 'Finished task with a past due date', { ...inProject, status: 'done', dueDate: addDays(today, -3) }),
    testTask(context, 'Task without a due date', inProject),
  ];
  const bugs: Bug[] = [
    testBug(context, 'Critical crash on start', { ...inProject, priority: 'critical' }),
    testBug(context, 'High priority bug, overdue', { ...inProject, priority: 'high', status: 'in_progress', dueDate: addDays(today, -1) }),
    testBug(context, 'Low priority glitch', { ...inProject, priority: 'low', dueDate: addDays(today, 5) }),
    testBug(context, 'Fixed bug', { ...inProject, status: 'fixed' }),
    testBug(context, 'Closed bug', { status: 'closed', priority: 'medium' }),
  ];
  const notes: Note[] = [
    {
      ...base(context),
      title: `${TEST_TITLE_PREFIX}Markdown note`,
      content: '## Test note\n\nSome **bold** and *italic* text, a list and code:\n\n- one\n- two\n\n```ts\nconst answer = 42;\n```\n',
      ...inProject,
    },
    { ...base(context), title: `${TEST_TITLE_PREFIX}Plain note`, content: 'A plain note without a project.', projectId: null },
  ];
  const snippets: Snippet[] = [
    {
      ...base(context),
      title: `${TEST_TITLE_PREFIX}Debounce`,
      language: 'TypeScript',
      code: 'export function debounce(fn: () => void, ms: number) {\n  let timer: ReturnType<typeof setTimeout>;\n  return () => {\n    clearTimeout(timer);\n    timer = setTimeout(fn, ms);\n  };\n}',
      description: 'Generated by the developer tools.',
      ...inProject,
    },
    { ...base(context), title: `${TEST_TITLE_PREFIX}Lua print`, language: 'Lua', code: 'print("hello from VOID")', description: '', projectId: null },
  ];
  return {
    ...workspace,
    projects: [project, ...workspace.projects],
    tasks: [...tasks, ...workspace.tasks],
    bugs: [...bugs, ...workspace.bugs],
    notes: [...notes, ...workspace.notes],
    snippets: [...snippets, ...workspace.snippets],
  };
}

export type DueDateTestCase = 'today' | 'tomorrow' | 'overdue' | 'week';

export const DUE_DATE_TEST_CASES: Record<DueDateTestCase, { label: string; offset: number }> = {
  today: { label: 'Due today', offset: 0 },
  tomorrow: { label: 'Due tomorrow', offset: 1 },
  overdue: { label: 'Overdue', offset: -3 },
  week: { label: 'Due in 7 days', offset: 7 },
};

/** Adds one test task with the given due date, relative to today. */
export function addDueDateTestTask(workspace: Workspace, which: DueDateTestCase, context: TestDataContext): Workspace {
  const { label, offset } = DUE_DATE_TEST_CASES[which];
  const task = testTask(context, label, { dueDate: addDays(toDayKey(context.now), offset) });
  return { ...workspace, tasks: [task, ...workspace.tasks] };
}

/**
 * Removes every item with a `devtest-` id. Nothing else is deleted: real
 * items that point to a removed test project are kept without a project, and
 * test tags are taken off real items.
 */
export function removeTestData(workspace: Workspace): Workspace {
  const keep = <T extends { id: string }>(items: T[]): T[] => items.filter((item) => !isTestId(item.id));
  const unlink = <T extends { projectId: string | null; tagIds: string[] }>(items: T[]): T[] =>
    items.map((item) => {
      const projectId = item.projectId !== null && isTestId(item.projectId) ? null : item.projectId;
      const tagIds = item.tagIds.filter((id) => !isTestId(id));
      return projectId === item.projectId && tagIds.length === item.tagIds.length ? item : { ...item, projectId, tagIds };
    });
  return {
    ...workspace,
    projects: keep(workspace.projects).map((project) => {
      const tagIds = project.tagIds.filter((id) => !isTestId(id));
      return tagIds.length === project.tagIds.length ? project : { ...project, tagIds };
    }),
    tasks: unlink(keep(workspace.tasks)),
    bugs: unlink(keep(workspace.bugs)),
    notes: unlink(keep(workspace.notes)),
    snippets: unlink(keep(workspace.snippets)),
    tags: keep(workspace.tags),
  };
}
